#!/usr/bin/env python3
"""Integration check: storm_schema -> Atlas -> verify the resulting DB structure (issue #773).

Ported from scripts/ci/test-atlas-migration.sh. Runs the built `storm_schema` tool, applies
its SQLite output with the real `atlas` CLI to a scratch database, and checks that the
expected tables, `Person` columns and indexes exist, that a second apply is a no-op and that
the versioned migrations validate. Names are compared whole, never as substrings (#771):
`idx_Person_department` must not pass on a DB that only has `idx_Person_department_age`.

Needs the `atlas` CLI and a built `storm_schema`, so it runs in CI's "Atlas integration
test" step, not in `script-guards`; scripts/ci/tests/test_atlas_migration_check.py drives it
against stubs of both. Stdlib only (the `sqlite3` module replaces the sqlite3 CLI), no syntax
newer than Python 3.7.

    scripts/ci/atlas_migration_check.py [--build-dir build/debug]
"""
import argparse
import os
import pathlib
import re
import shutil
import sqlite3
import subprocess
import sys
import tempfile

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA_BIN_RELATIVE = pathlib.Path("tests") / "tools" / "storm_schema" / "storm_schema"
DEV_URL = "sqlite://dev?mode=memory"

SQLITE_TABLES = ("Person", "Message", "SimpleRecord", "ExtendedTypes", "Task")
APPLIED_TABLES = ("Person", "SimpleRecord", "Message", "ExtendedTypes", "Task")
PERSON_COLUMNS = ("id", "name", "age", "salary", "department")
INDEXES = ("idx_Person_department", "idx_Person_department_age", "idx_Person_name_department",
           "idx_Message_sender_id", "idx_Task_assignee_id")
PG_IDENTITY = "GENERATED BY DEFAULT AS IDENTITY"
SYNCED_MARKER = "Schema is synced"


class Report(object):
    """Counts PASS/FAIL lines and prints them; colour only on a terminal without NO_COLOR."""

    def __init__(self, out):
        self.out = out
        self.passed = 0
        self.failed = 0
        self.colour = (out.isatty() or "GITHUB_ACTIONS" in os.environ) and "NO_COLOR" not in os.environ

    def paint(self, code, text):
        return "\033[%sm%s\033[0m" % (code, text) if self.colour else text

    def heading(self, text):
        print(self.paint("1;33", text), file=self.out)

    def check(self, condition, message, detail=""):
        """`detail` (a tool's output) is shown under a FAILED check, so a CI-only failure
        says why."""
        if condition:
            self.passed += 1
        else:
            self.failed += 1
        label = self.paint("0;32", "PASS") if condition else self.paint("0;31", "FAIL")
        print("  %s %s" % (label, message), file=self.out)
        if detail and not condition:
            print("".join("    | %s\n" % line for line in detail.splitlines()), end="", file=self.out)

    def error(self, text):
        print(self.paint("0;31", text), file=self.out)


def run_tool(command):
    """(returncode, stdout and stderr merged) of `command`."""
    result = subprocess.run([str(part) for part in command], stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, universal_newlines=True)
    return result.returncode, result.stdout


def names_from(database, query):
    """First column of every row, or [] when the database cannot be read - an unreadable DB
    must fail every existence check, not raise."""
    try:
        connection = sqlite3.connect(database.as_uri() + "?mode=ro", uri=True)
        try:
            return [row[0] for row in connection.execute(query)]
        finally:
            connection.close()
    except sqlite3.Error:
        return []


def atlas_apply(database, schema_file):
    return run_tool(["atlas", "schema", "apply", "--url", "sqlite://%s" % database,
                     "--to", "file://%s" % schema_file, "--dev-url", DEV_URL, "--auto-approve"])


def check_schema_export(report, schema_bin, scratch):
    """Returns the SQLite schema path, or None when storm_schema itself failed."""
    report.heading("1. Schema export")
    files = (("SQLite", scratch / "schema_sqlite.sql", []),
             ("PostgreSQL", scratch / "schema_pg.sql", ["--dialect", "postgresql"]))
    texts = {}
    for label, path, extra in files:
        returncode, output = run_tool([schema_bin] + extra + ["--output", path])
        if returncode != 0:
            report.error("storm_schema failed (exit %d):\n%s" % (returncode, output))
            return None
        texts[label] = path.read_text() if path.is_file() else ""
        report.check(bool(texts[label]), "%s schema file generated" % label)
    for table in SQLITE_TABLES:
        # Anchored on the opening paren so "Task" does not also match "TaskLog".
        found = re.search(r"^CREATE TABLE %s \(" % re.escape(table), texts["SQLite"], re.MULTILINE)
        report.check(found is not None, "SQLite: CREATE TABLE %s" % table)
    report.check(PG_IDENTITY in texts["PostgreSQL"], "PostgreSQL: %s" % PG_IDENTITY)
    return files[0][1]


def check_applied_schema(report, schema_file, database):
    report.heading("\n2. Atlas schema apply (declarative)")
    returncode, output = atlas_apply(database, schema_file)
    report.check(returncode == 0, "atlas schema apply succeeds", output)
    tables = names_from(database, "SELECT name FROM sqlite_master WHERE type='table'")
    for table in APPLIED_TABLES:
        report.check(table in tables, "%s table exists" % table)
    columns = names_from(database, "SELECT name FROM pragma_table_info('Person')")
    for column in PERSON_COLUMNS:
        report.check(column in columns, "Person.%s column exists" % column)
    indexes = names_from(database, "SELECT name FROM sqlite_master WHERE type='index'")
    for index in INDEXES:
        report.check(index in indexes, "%s index exists" % index)


def check_idempotency(report, schema_file, database):
    report.heading("\n3. Idempotency")
    _, output = atlas_apply(database, schema_file)
    report.check(SYNCED_MARKER in output, "Re-apply is no-op", output)


def check_migrations(report, migrations_dir):
    report.heading("\n4. Versioned migration validate")
    if not migrations_dir.is_dir():
        print("  SKIP No migrations/ directory", file=report.out)
        return
    returncode, output = run_tool(["atlas", "migrate", "validate", "--dir", "file://%s" % migrations_dir,
                                   "--dev-url", DEV_URL])
    report.check(returncode == 0, "atlas migrate validate passes", output)


def prerequisite_problem(schema_bin):
    if not shutil.which("atlas"):
        return "atlas CLI not found. Install: curl -sSf https://atlasgo.sh | sh"
    if not (schema_bin.is_file() and os.access(str(schema_bin), os.X_OK)):
        return ("storm_schema not found at %s\n"
                "Build it first: cmake --build --preset ninja-debug --target storm_schema" % schema_bin)
    return None


def parse_arguments(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build-dir", type=pathlib.Path, default=REPO_ROOT / "build" / "debug")
    parser.add_argument("--migrations-dir", type=pathlib.Path,
                        default=REPO_ROOT / "tests" / "tools" / "migrations")
    return parser.parse_args(argv)


def main(argv=None, out=None):
    arguments = parse_arguments(sys.argv[1:] if argv is None else argv)
    report = Report(out or sys.stdout)
    schema_bin = arguments.build_dir / SCHEMA_BIN_RELATIVE
    report.heading("=== Storm Atlas Integration Test ===\n")
    problem = prerequisite_problem(schema_bin)
    if problem:
        report.error(problem)
        return 1
    with tempfile.TemporaryDirectory(prefix="storm_atlas_test_") as tmp:
        scratch = pathlib.Path(tmp)
        schema_file = check_schema_export(report, schema_bin, scratch)
        if schema_file is None:
            return 1
        database = scratch / "test.db"
        check_applied_schema(report, schema_file, database)
        check_idempotency(report, schema_file, database)
        check_migrations(report, arguments.migrations_dir)
    total = report.passed + report.failed
    print("\n" + report.paint("1;33", "=== Results: %d/%d passed ===" % (report.passed, total)), file=report.out)
    if report.failed:
        report.error("%d test(s) failed" % report.failed)
        return 1
    print(report.paint("0;32", "All tests passed"), file=report.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

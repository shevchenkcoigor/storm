#!/usr/bin/env python3
"""Tests for scripts/ci/atlas_migration_check.py (issue #773, ported from bash in #771/#773).

The check runs the built `storm_schema` and the real `atlas` CLI, neither of which exists in
`script-guards`. Both are replaced by stubs: `storm_schema` copies a fixture SQL file to
`--output`, and `atlas` applies that SQL to a scratch SQLite DB (so the checks read a real
database). A mutation of the applied DB or the SQL stands in for "the schema came out wrong";
each must fail exactly the matching check - above all the ones a substring match used to
let through (#771): `idx_Person_department` on a DB that only has `idx_Person_department_age`.
Stdlib unittest, no syntax newer than Python 3.7.

    python3 scripts/ci/tests/test_atlas_migration_check.py
"""
import os
import pathlib
import re
import sys
import tempfile
import unittest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO_ROOT / "scripts" / "lib"))
import testing  # noqa: E402

sys.path.insert(0, str(REPO_ROOT / "scripts" / "ci"))
import atlas_migration_check as check  # noqa: E402

CHECK = REPO_ROOT / "scripts" / "ci" / "atlas_migration_check.py"

SQLITE_SQL = """\
CREATE TABLE Person (id INTEGER PRIMARY KEY, name TEXT NOT NULL, age INTEGER, salary REAL, department TEXT);
CREATE INDEX IF NOT EXISTS idx_Person_department ON Person(department);
CREATE INDEX IF NOT EXISTS idx_Person_department_age ON Person(department, age);
CREATE INDEX IF NOT EXISTS idx_Person_name_department ON Person(name, department);
CREATE TABLE SimpleRecord (id INTEGER PRIMARY KEY);
CREATE TABLE Message (id INTEGER PRIMARY KEY, sender_id INTEGER);
CREATE INDEX IF NOT EXISTS idx_Message_sender_id ON Message(sender_id);
CREATE TABLE ExtendedTypes (id INTEGER PRIMARY KEY);
CREATE TABLE Task (id INTEGER PRIMARY KEY, assignee_id INTEGER);
CREATE INDEX IF NOT EXISTS idx_Task_assignee_id ON Task(assignee_id);
"""
PG_SQL = "CREATE TABLE Person (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);\n"

STORM_SCHEMA_STUB = """#!{python}
import os, shutil, sys
args = sys.argv[1:]
if os.environ.get("STUB_SCHEMA_RC"):
    print("boom")
    sys.exit(int(os.environ["STUB_SCHEMA_RC"]))
source = os.environ["STUB_PG_SQL" if "postgresql" in args else "STUB_SQLITE_SQL"]
shutil.copy(source, args[args.index("--output") + 1])
"""

ATLAS_STUB = """#!{python}
import os, sqlite3, sys
args = sys.argv[1:]
if args[:2] == ["schema", "apply"]:
    options = dict(zip(args[2::2], args[3::2]))
    database = options["--url"][len("sqlite://"):]
    if os.environ.get("STUB_APPLY_RC"):
        print("apply exploded")
        sys.exit(int(os.environ["STUB_APPLY_RC"]))
    connection = sqlite3.connect(database)
    if connection.execute("SELECT count(*) FROM sqlite_master").fetchone()[0]:
        print("changes applied" if os.environ.get("STUB_NOT_SYNCED") else "Schema is synced, no changes to be made")
        sys.exit(0)
    connection.executescript(open(options["--to"][len("file://"):]).read())
    if os.environ.get("STUB_MUTATE"):
        connection.executescript(os.environ["STUB_MUTATE"])
    connection.commit()
    print("applied")
    sys.exit(0)
if args[:2] == ["migrate", "validate"]:
    if os.environ.get("STUB_VALIDATE_RC", "0") != "0":
        print("validate exploded")
    sys.exit(int(os.environ.get("STUB_VALIDATE_RC", "0")))
sys.exit(2)
"""


def failures(output):
    """The messages of every FAIL line, in order."""
    return re.findall(r"^  FAIL (.*)$", output, re.MULTILINE)


class AtlasMigrationCheckTest(unittest.TestCase):
    def setUp(self):
        scratch = tempfile.TemporaryDirectory()
        self.addCleanup(scratch.cleanup)
        self.tmp = pathlib.Path(os.path.realpath(scratch.name))
        self.bin = self.tmp / "bin"
        self.build = self.tmp / "build"
        self.migrations = self.tmp / "migrations"
        self.migrations.mkdir()
        self.install_stub(self.bin / "atlas", ATLAS_STUB)
        self.install_stub(self.build / "tests" / "tools" / "storm_schema" / "storm_schema", STORM_SCHEMA_STUB)
        self.sqlite_sql = self.write("sqlite.sql", SQLITE_SQL)
        self.pg_sql = self.write("pg.sql", PG_SQL)

    def install_stub(self, path, template):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(template.format(python=sys.executable))
        path.chmod(0o755)

    def write(self, name, text):
        path = self.tmp / name
        path.write_text(text)
        return path

    def run_check(self, stub_env=None, path_dirs=None, migrations=None):
        """(returncode, output). `path_dirs` replaces PATH (to hide the atlas stub)."""
        env = {"PATH": os.pathsep.join(path_dirs if path_dirs is not None else [str(self.bin)]),
               "STUB_SQLITE_SQL": str(self.sqlite_sql), "STUB_PG_SQL": str(self.pg_sql)}
        env.update(stub_env or {})
        result = testing.run([sys.executable, CHECK, "--build-dir", self.build,
                              "--migrations-dir", migrations or self.migrations],
                             env=env, merge_stderr=True)
        return result.returncode, result.stdout

    def assert_fails_only(self, stub_env, expected):
        returncode, output = self.run_check(stub_env)
        self.assertEqual(failures(output), expected, output)
        self.assertEqual(returncode, 1)

    # --- Scenarios ---

    def test_a_correct_schema_passes_every_check(self):
        returncode, output = self.run_check()
        self.assertEqual((returncode, failures(output)), (0, []), output)
        self.assertIn("Results: 26/26 passed", output)

    def test_an_index_that_is_only_a_prefix_of_another_does_not_pass(self):
        # idx_Person_department_age remains: a substring match would have called this green.
        self.assert_fails_only({"STUB_MUTATE": "DROP INDEX idx_Person_department;"},
                               ["idx_Person_department index exists"])

    def test_a_renamed_column_fails_its_check(self):
        self.assert_fails_only({"STUB_MUTATE": "ALTER TABLE Person RENAME COLUMN salary TO salary_old;"},
                               ["Person.salary column exists"])

    def test_a_column_named_like_the_header_row_is_still_checked(self):
        self.assert_fails_only({"STUB_MUTATE": "ALTER TABLE Person RENAME COLUMN name TO name_old;"},
                               ["Person.name column exists"])

    def test_a_renamed_table_fails_its_check(self):
        self.assert_fails_only({"STUB_MUTATE": "ALTER TABLE Task RENAME TO TaskLog;"},
                               ["Task table exists"])

    def test_a_table_whose_name_extends_the_expected_one_fails_the_schema_file_check(self):
        self.sqlite_sql = self.write("sqlite.sql", SQLITE_SQL.replace("TABLE Task (", "TABLE TaskLog (")
                                     .replace("ON Task(", "ON TaskLog("))
        returncode, output = self.run_check()
        self.assertIn("SQLite: CREATE TABLE Task", failures(output), output)
        self.assertEqual(returncode, 1)

    def test_a_postgres_schema_without_identity_columns_fails(self):
        self.pg_sql = self.write("pg.sql", "CREATE TABLE Person (id BIGINT PRIMARY KEY);\n")
        returncode, output = self.run_check()
        self.assertEqual(failures(output), ["PostgreSQL: GENERATED BY DEFAULT AS IDENTITY"], output)
        self.assertEqual(returncode, 1)

    def test_a_reapply_that_changes_something_fails(self):
        self.assert_fails_only({"STUB_NOT_SYNCED": "1"}, ["Re-apply is no-op"])

    def test_a_failed_apply_fails_its_check_and_everything_that_needed_the_database(self):
        returncode, output = self.run_check({"STUB_APPLY_RC": "1"})
        found = failures(output)
        self.assertIn("atlas schema apply succeeds", found)
        self.assertIn("Person table exists", found)
        self.assertIn("Re-apply is no-op", found)
        self.assertIn("    | apply exploded", output, "the tool's output is shown under the FAIL line")
        self.assertEqual(returncode, 1)

    def test_migrations_that_do_not_validate_fail(self):
        returncode, output = self.run_check({"STUB_VALIDATE_RC": "1"})
        self.assertEqual(failures(output), ["atlas migrate validate passes"], output)
        self.assertIn("    | validate exploded", output)
        self.assertEqual(returncode, 1)

    def test_the_defaults_point_at_real_places(self):
        # Every other test passes --build-dir / --migrations-dir; CI passes neither, and a
        # wrong default would turn step 4 into a silent SKIP (or fail step 1 loudly).
        arguments = check.parse_arguments([])
        self.assertTrue(arguments.migrations_dir.is_dir(), arguments.migrations_dir)
        self.assertEqual(arguments.build_dir, REPO_ROOT / "build" / "debug")
        self.assertTrue((REPO_ROOT / "tests" / "tools" / "storm_schema").is_dir())

    def test_a_missing_migrations_directory_is_skipped_not_failed(self):
        returncode, output = self.run_check(migrations=self.tmp / "absent")
        self.assertEqual((returncode, failures(output)), (0, []), output)
        self.assertIn("SKIP No migrations/ directory", output)

    def test_a_missing_atlas_cli_stops_the_run(self):
        returncode, output = self.run_check(path_dirs=[str(self.tmp / "empty")])
        self.assertEqual(returncode, 1)
        self.assertIn("atlas CLI not found", output)

    def test_a_missing_storm_schema_stops_the_run(self):
        (self.build / "tests" / "tools" / "storm_schema" / "storm_schema").unlink()
        returncode, output = self.run_check()
        self.assertEqual(returncode, 1)
        self.assertIn("storm_schema not found", output)

    def test_a_failing_storm_schema_stops_the_run(self):
        returncode, output = self.run_check({"STUB_SCHEMA_RC": "3"})
        self.assertEqual(returncode, 1)
        self.assertIn("storm_schema failed (exit 3)", output)
        self.assertNotIn("atlas schema apply", output)


if __name__ == "__main__":
    unittest.main()

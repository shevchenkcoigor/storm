#!/bin/bash
# Tests for scripts/lib/line_coverage.sh and its caller in commit.sh (#680).
#
# commit.sh's coverage step used to read the percentage with `grep -oP`. macOS
# ships BSD grep, which has no -P, so on every Mac the step printed "Could not
# parse line coverage from output." and blocked the commit after format, tidy
# and tests had all passed. CI runs GNU grep and never noticed.
#
# To catch that on a Linux runner too, every check runs with a `grep` shim first
# on PATH that rejects GNU-only usage (-P/--perl-regexp, PCRE-only syntax such as
# `\d` or `(?=`) before handing off to the real grep. Without it, GNU grep runs
# `grep -oP` happily and the test passes on CI even with the bug restored.
# On a Mac the real grep underneath can also be forced to BSD grep with
#   PATH=/usr/bin:/bin scripts/tests/test_line_coverage.sh
#
# Like test_pg_default_connstr.sh, the commit.sh check is behavioural: it runs
# the real run_coverage_check() text with `cmake` stubbed out, so a deleted
# `source` line or a reintroduced GNU-only flag changes the result.

set -u

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HELPER="$REPO_ROOT/scripts/lib/line_coverage.sh"
COMMIT="$REPO_ROOT/commit.sh"

PASS=0
FAIL=0

check() {
    local name="$1" expected="$2" actual="$3"
    if [[ "$expected" == "$actual" ]]; then
        echo "  PASS: $name"
        PASS=$((PASS+1))
    else
        echo "  FAIL: $name"
        echo "        expected: [$expected]"
        echo "        actual:   [$actual]"
        FAIL=$((FAIL+1))
    fi
    return 0
}

REAL_GREP="$(command -v grep)"
echo "grep under test: $REAL_GREP (behind a BSD-portability shim)"

# The shim. Exported PATH, so the helper checks, the `bash -c` that runs
# commit.sh's function and anything they spawn all resolve `grep` to it.
SHIM_DIR="$(mktemp -d)"
trap 'rm -rf "$SHIM_DIR"' EXIT
cat > "$SHIM_DIR/grep" <<EOF
#!/bin/bash
# Fails loudly on grep usage BSD grep (macOS) does not support, then defers to
# the real grep. Generated by scripts/tests/test_line_coverage.sh (#680).
for arg in "\$@"; do
    case "\$arg" in
        --perl-regexp|--perl-regexp=*) bad="\$arg" ;;
        --*) ;;
        -*P*) bad="\$arg (-P)" ;;
    esac
    case "\$arg" in
        *'\\d'*|*'\\K'*|*'(?='*|*'(?!'*|*'(?<'*) bad="\$arg (PCRE-only syntax)" ;;
    esac
    if [[ -n "\${bad:-}" ]]; then
        echo "grep shim: GNU-only grep usage rejected: \$bad" >&2
        exit 2
    fi
done
exec "$REAL_GREP" "\$@"
EOF
chmod +x "$SHIM_DIR/grep"
export PATH="$SHIM_DIR:$PATH"

# Self-check the shim, so a broken shim cannot make every check vacuous.
check "shim rejects -oP" "2" \
    "$(echo 1% | grep -oP '[0-9]+(?=%)' 2>/dev/null; echo $?)"
check "shim rejects PCRE syntax without -P" "2" \
    "$(echo 1 | grep -E '\d' 2>/dev/null; echo $?)"
check "shim passes portable usage through" "1%" \
    "$(echo 1% | grep -oE '[0-9]+%')"

# A realistic `lcov --summary` (lcov 2.x) as printed by the coverage target. The
# functions/branches rows carry percentages too: anchoring on the wrong row
# would gate against ~81% or ~92%.
summary() { # <line-percent>
    printf '%s\n' \
        "[100%] Built target coverage-run" \
        "Summary coverage rate:" \
        "  source files: 24" \
        "  lines.......: $1% (8613 of 8613 lines)" \
        "  functions...: 80.6% (4100 of 5087 functions)" \
        "  branches....: 92.1% (812 of 882 branches)"
    return 0
}

# --- The helper ---

if [[ -f "$HELPER" ]]; then
    # shellcheck source=../lib/line_coverage.sh
    source "$HELPER"

    check "full coverage parses as 100.0" "100.0" \
        "$(summary 100.0 | storm_parse_line_coverage)"
    check "partial coverage parses as 99.8" "99.8" \
        "$(summary 99.8 | storm_parse_line_coverage)"
    check "the lines row wins over functions/branches" "97.3" \
        "$(summary 97.3 | storm_parse_line_coverage)"
    check "the last lines row wins" "100.0" \
        "$( { summary 42.0; summary 100.0; } | storm_parse_line_coverage)"
    check "no lines row yields nothing" "" \
        "$(printf 'error: build failed\n  functions...: 80.6%% (1 of 2)\n' | storm_parse_line_coverage)"
    check "empty input yields nothing" "" \
        "$(storm_parse_line_coverage < /dev/null)"

    # CI calls it from a `bash -eo pipefail` step; a no-match must still come
    # back as an empty value for the caller's own loud error, not kill the step.
    check "no match under set -eo pipefail returns empty, rc 0" "rc=0 val=[]" \
        "$(bash -c "set -eo pipefail; source '$HELPER'
               v=\$(printf 'nothing\n' | storm_parse_line_coverage)
               printf 'rc=%s val=[%s]' \$? \"\$v\"")"
else
    check "$HELPER exists" "yes" "no"
fi

# --- commit.sh's run_coverage_check() ---
# Extract the real function, stub `cmake` to print a summary, and read what it
# reports. BASH_SOURCE[0] is swapped for commit.sh's absolute path on purpose:
# the hook runs ./commit.sh from the work-tree top, and this resolves the
# helper's `source` to the same file wherever the test is run from.
run_commit_check() { # <line-percent>
    local percent="$1" block
    block="$(sed -n '/^    run_coverage_check() {/,/^    }$/p' "$COMMIT")"
    block="${block//'${BASH_SOURCE[0]}'/$COMMIT}"
    bash -c "RED= BOLD= RESET= DIM=
$(declare -f summary)
cmake() { [[ \"\$*\" == *'--target coverage' ]] && summary '$percent'; return 0; }
show_uncovered_lines() { echo '<uncovered>'; }
$block
run_coverage_check; echo \"rc=\$?\"" 2>&1
    return 0
}

full_out="$(run_commit_check 100.0)"
check "commit.sh: 100.0% passes the gate" "Line coverage: 100.0%|rc=0" \
    "$(grep -E '^(Line coverage|rc=)' <<< "$full_out" | paste -sd '|' -)"

partial_out="$(run_commit_check 99.8)"
check "commit.sh: 99.8% fails the gate with the real number" \
    "Line coverage: 99.8% (required: 100.0%)|<uncovered>|rc=1" \
    "$(grep -E '^(Line coverage|<uncovered>|rc=)' <<< "$partial_out" | paste -sd '|' -)"

if [[ "$full_out" == *"Could not parse"* || "$partial_out" == *"Could not parse"* ]]; then
    echo "        commit.sh output was:"
    sed 's/^/          /' <<< "$full_out"
fi

echo "$PASS passed, $FAIL failed"
[[ $FAIL -eq 0 ]]

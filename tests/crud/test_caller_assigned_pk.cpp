template <typename ConnType> class CallerAssignedPkUpsertTest : public StormTestFixture<Person, ConnType> {
  public:
    auto on_setup(const std::shared_ptr<ConnType>& conn) -> void override {
        const std::string ddl = storm::test::is_postgresql<ConnType>()
                                        ? create_table_sql<AssignedIdRec, Dialect::PostgreSQL>()
                                        : create_table_sql<AssignedIdRec>();
        ASSERT_TRUE(conn->execute(ddl).has_value()) << ddl;
    }
};

TYPED_TEST_SUITE(CallerAssignedPkUpsertTest, DatabaseTypes);

TYPED_TEST(CallerAssignedPkUpsertTest, DoNothingSkipsOnDuplicateKey) {
    InsertStatement<AssignedIdRec, TypeParam> qs;
    ASSERT_TRUE(qs.query(AssignedIdRec{.ext_id = 200, .label = "original"}).execute().has_value());

    auto upserted = InsertStatement<AssignedIdRec, TypeParam>{}
                            .query(AssignedIdRec{.ext_id = 200, .label = "clash"})
                            .template on_conflict<fields::AssignedIdRec.ext_id>()
                            .nothing()
                            .execute();

    static_assert(
            std::is_same_v<decltype(upserted), std::expected<void, typename TypeParam::Error>>,
            "DO NOTHING on a caller-assigned-PK model returns void"
    );
    ASSERT_TRUE(upserted.has_value()) << upserted.error().message();

    auto selected = SelectStatement<AssignedIdRec, TypeParam>().execute();
    ASSERT_TRUE(selected.has_value()) << selected.error().message();
    ASSERT_EQ(selected.value().size(), 1U);
    EXPECT_EQ(selected.value().begin()->label, "original") << "DO NOTHING must not overwrite";
}

TYPED_TEST(CallerAssignedPkUpsertTest, DoUpdateOverwritesOnDuplicateKey) {
    InsertStatement<AssignedIdRec, TypeParam> qs;
    ASSERT_TRUE(qs.query(AssignedIdRec{.ext_id = 300, .label = "old"}).execute().has_value());

    auto upserted = InsertStatement<AssignedIdRec, TypeParam>{}
                            .query(AssignedIdRec{.ext_id = 300, .label = "new"})
                            .template on_conflict<fields::AssignedIdRec.ext_id>()
                            .template update<fields::AssignedIdRec.label>()
                            .execute();

    static_assert(
            std::is_same_v<decltype(upserted), std::expected<void, typename TypeParam::Error>>,
            "DO UPDATE on a caller-assigned-PK model returns void"
    );
    ASSERT_TRUE(upserted.has_value()) << upserted.error().message();

    auto selected = SelectStatement<AssignedIdRec, TypeParam>().where(fields::AssignedIdRec.ext_id == 300).execute();
    ASSERT_TRUE(selected.has_value()) << selected.error().message();
    ASSERT_EQ(selected.value().size(), 1U);
    EXPECT_EQ(selected.value().begin()->label, "new") << "DO UPDATE must overwrite the listed column";
}


template <typename ConnType> class CallerAssignedPkCrudTest : public StormTestFixture<Person, ConnType> {
  public:
    auto on_setup(const std::shared_ptr<ConnType>& conn) -> void override {
        const std::string ddl = storm::test::is_postgresql<ConnType>()
                                        ? create_table_sql<AssignedIdRec, Dialect::PostgreSQL>()
                                        : create_table_sql<AssignedIdRec>();
        ASSERT_TRUE(conn->execute(ddl).has_value()) << ddl;
    }
};

TYPED_TEST_SUITE(CallerAssignedPkCrudTest, DatabaseTypes);

TYPED_TEST(CallerAssignedPkCrudTest, InsertPersistsCallerSuppliedId) {
    InsertStatement<AssignedIdRec, TypeParam> qs;
    const AssignedIdRec                       row{.ext_id = 42, .label = "imported"};
    auto                                      result = qs.query(row).execute();

    static_assert(
            std::is_same_v<decltype(result), std::expected<void, typename TypeParam::Error>>,
            "insert() on a caller-assigned-PK model returns void — nothing to RETURN"
    );
    ASSERT_TRUE(result.has_value()) << result.error().message();

    auto selected = SelectStatement<AssignedIdRec, TypeParam>().execute();
    ASSERT_TRUE(selected.has_value()) << selected.error().message();
    ASSERT_EQ(selected.value().size(), 1U);
    const auto& loaded = *selected.value().begin();
    EXPECT_EQ(loaded.ext_id, 42) << "the caller's id value must survive round-trip";
    EXPECT_EQ(loaded.label, "imported");
}

TYPED_TEST(CallerAssignedPkCrudTest, InsertWithZeroIdPersistsZero) {
    InsertStatement<AssignedIdRec, TypeParam> qs;
    const AssignedIdRec                       row{.ext_id = 0, .label = "zero"};
    auto                                      result = qs.query(row).execute();
    ASSERT_TRUE(result.has_value()) << result.error().message();

    auto selected = SelectStatement<AssignedIdRec, TypeParam>().where(fields::AssignedIdRec.ext_id == 0).execute();
    ASSERT_TRUE(selected.has_value()) << selected.error().message();
    ASSERT_EQ(selected.value().size(), 1U);
    EXPECT_EQ(selected.value().begin()->label, "zero");
}

TYPED_TEST(CallerAssignedPkCrudTest, SecondInsertWithSameIdIsDuplicateError) {
    InsertStatement<AssignedIdRec, TypeParam> qs;
    ASSERT_TRUE(qs.query(AssignedIdRec{.ext_id = 100, .label = "first"}).execute().has_value());

    auto duplicate = InsertStatement<AssignedIdRec, TypeParam>{}
                             .query(AssignedIdRec{.ext_id = 100, .label = "second"})
                             .execute();
    EXPECT_FALSE(duplicate.has_value()) << "duplicate caller-assigned PK must be rejected by the database";
}

